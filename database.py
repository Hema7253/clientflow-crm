
import os
import sqlite3

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATABASE = os.path.join(BASE_DIR, "database.db")


# --------------------------------------------------
# ROW HANDLING
# --------------------------------------------------

class HybridRow(dict):
    """Allow row access by column name or numeric index."""

    def __init__(self, columns, values):
        super().__init__(zip(columns, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def postgres_row_factory(cursor):
    """
    Return a row factory.

    IMPORTANT: cursor.description is read only when a row
    is fetched, after the SQL query has been executed.
    """

    def make_row(values):
        description = cursor.description

        if description is None:
            return values

        columns = [column.name for column in description]
        return HybridRow(columns, values)

    return make_row


# --------------------------------------------------
# DATABASE CONNECTION WRAPPER
# --------------------------------------------------

class DatabaseConnection:
    """Common interface for SQLite and PostgreSQL connections."""

    def __init__(self, connection, is_postgres=False):
        self.connection = connection
        self.is_postgres = is_postgres

    def execute(self, sql, parameters=()):
        if self.is_postgres:
            sql = sql.replace("?", "%s")

        return self.connection.execute(sql, parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


# --------------------------------------------------
# CONNECT TO SQLITE OR NEON POSTGRESQL
# --------------------------------------------------

def get_db_connection():
    database_url = os.environ.get("DATABASE_URL", "").strip()

    if database_url:
        import psycopg

        connection = psycopg.connect(
            database_url,
            row_factory=postgres_row_factory
        )

        return DatabaseConnection(
            connection,
            is_postgres=True
        )

    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")

    return DatabaseConnection(
        connection,
        is_postgres=False
    )


# --------------------------------------------------
# CREATE DATABASE TABLES
# --------------------------------------------------

def create_database():
    connection = get_db_connection()

    try:
        if connection.is_postgres:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS clients (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT,
                    phone TEXT,
                    company TEXT
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS projects (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    project_name TEXT NOT NULL,
                    client_id INTEGER NOT NULL,
                    budget DOUBLE PRECISION DEFAULT 0,
                    status TEXT DEFAULT 'Active',
                    deadline TEXT,
                    FOREIGN KEY (client_id)
                        REFERENCES clients(id)
                        ON DELETE RESTRICT
                )
            """)

        else:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS clients (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    email TEXT,
                    phone TEXT,
                    company TEXT
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS projects (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    project_name TEXT NOT NULL,
                    client_id INTEGER NOT NULL,
                    budget REAL DEFAULT 0,
                    status TEXT DEFAULT 'Active',
                    deadline TEXT,
                    FOREIGN KEY (client_id)
                        REFERENCES clients(id)
                        ON DELETE RESTRICT
                )
            """)

        connection.commit()
        print("Database and tables are ready!")

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


